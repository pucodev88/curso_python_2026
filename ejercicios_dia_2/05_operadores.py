# Suma: +
# Resta: -
# Multiplicacion: * 
# Division con decimales /
# Division entera //
# Modulo %
# Potencia **
numero_1 = 1
numero_2 = 2
suma = numero_1 + numero_2
resta = 10 - 1
multiplicacion = 10 * 10
division_normal = 100 / 5
division_con_parte_entera = 10 // 3
residuo = 10 % 2
potencia = 3 ** 3

print(
    suma,
    resta,
    multiplicacion,
    division_normal,
    division_con_parte_entera,
    residuo,
    potencia
)
 